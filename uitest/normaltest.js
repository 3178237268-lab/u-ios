const { chromium } = require('playwright-core');
const wait = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const b = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true });
  const p = await (await b.newContext()).newPage();
  const errs = [];
  p.on('pageerror', e => errs.push('PAGEERR ' + String(e).slice(0, 160)));
  p.on('console', m => { if (m.type() === 'error') errs.push('CONSOLE ' + m.text().slice(0, 160)); });
  await p.goto('http://127.0.0.1:8765/', { waitUntil: 'load' });
  await p.waitForTimeout(2500);
  const ok = [], fail = [];
  const step = async (name, fn) => { try { await fn(); ok.push(name); } catch (e) { fail.push(name + ' :: ' + e.message.split('\n')[0].slice(0, 90)); } };
  await step('游客登录', async () => { await p.locator('#guestBtn').click(); await wait(1500); });
  await step('时间线有帖', async () => { const n = await p.locator('.post').count(); if (!n) throw new Error('0'); });
  await step('打开发帖', async () => { await p.locator('#composeBtn').click(); await wait(700); });
  await step('发布', async () => { await p.locator('#composeText').fill('正常模式测试帖 ' + Date.now()); await p.locator('#composePublish').click(); await wait(2000); });
  await step('新帖在顶部', async () => { const t = await p.locator('.post .ptext').first().innerText(); if (!t.includes('正常模式测试帖')) throw new Error('first=' + t.slice(0, 16)); });
  await step('点赞', async () => { await p.locator('.post button[data-act="like"]').first().click({ timeout: 8000 }); await wait(800); });
  console.log('PASS ' + ok.length + '/' + (ok.length + fail.length)); fail.forEach(f => console.log('FAIL ' + f));
  console.log('errors', errs.length); errs.slice(0, 6).forEach(e => console.log(' ', e));
  await p.screenshot({ path: 'D:\\deepseek\\gouzuoqu\\U\\.tmp-test\\shots\\normal-post.png' });
  await b.close();
})();
