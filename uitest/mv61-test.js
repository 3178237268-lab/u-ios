const http = require('http');
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright-core');
const ROOT = 'D:/deepseek/gouzuoqu/U';
const PORT = 18933;
const CHROME = 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
const MIME = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml' };
const srv = http.createServer((req, res) => {
  let p = decodeURIComponent(req.url.split('?')[0]); if (p === '/') p = '/index.html';
  const f = path.join(ROOT, p);
  fs.readFile(f, (e, buf) => { if (e) { res.writeHead(404); res.end('nf'); return; } res.writeHead(200, { 'Content-Type': MIME[path.extname(f).toLowerCase()] || 'application/octet-stream' }); res.end(buf); });
});
const log = []; const ok = (n, c, x) => { log.push((c ? 'PASS ' : 'FAIL ') + n + (x ? ' | ' + x : '')); };
const sleep = (n) => new Promise(r => setTimeout(r, n));
(async () => {
  await new Promise(r => srv.listen(PORT, r));
  const browser = await chromium.launch({ executablePath: CHROME, headless: true, args: ['--no-sandbox', '--disable-gpu', '--autoplay-policy=no-user-gesture-required'] });
  const ctx = await browser.newContext({ viewport: { width: 420, height: 900 }, deviceScaleFactor: 2 });
  const page = await ctx.newPage(); const errs = []; page.on('pageerror', e => errs.push(String(e)));
  await page.goto('http://127.0.0.1:' + PORT + '/index.html');
  await page.evaluate(() => localStorage.setItem('u-server', 'http://127.0.0.1:8787'));
  await page.reload(); await sleep(700);
  await page.fill('#authUser', 'admin123'); await page.fill('#authPass', 'admin123');
  await page.click('#authSubmit'); await sleep(3000);
  const pid = await page.evaluate(() => { const a = Array.from(document.querySelectorAll('.post')).find(x => x.querySelectorAll('.vplayer.vgrid').length >= 2); return a ? a.dataset.id : null; });
  if (!pid) { console.log('no multi-video post'); process.exit(1); }
  await page.evaluate((id) => { document.querySelector('.post[data-id="' + id + '"]').scrollIntoView({ block: 'center' }); }, pid);
  await sleep(600);
  await page.evaluate((id) => { const a = document.querySelector('.post[data-id="' + id + '"]'); (a.querySelector('.vgexp') || a.querySelector('.vplayer')).click(); }, pid);
  await page.waitForSelector('#mediaViewer.open', { timeout: 8000 }); await sleep(1800);
  const box = await page.locator('#mvStage').boundingBox();
  const cx = box.x + box.width / 2, cy = box.y + box.height * 0.4;
  const tap = async () => { await page.mouse.move(cx, cy); await page.mouse.down(); await sleep(60); await page.mouse.up(); await sleep(450); };
  const st0 = await page.evaluate(() => ({ paused: document.querySelector('#mvContent video').paused }));
  await page.evaluate(() => { const v = document.querySelector('#mvContent video'); v.play().catch(() => {}); });
  await sleep(700);
  const playing = await page.evaluate(() => !document.querySelector('#mvContent video').paused);
  ok('视频在播', playing, JSON.stringify(st0));
  await tap();
  const s1 = await page.evaluate(() => ({ off: document.querySelector('#mediaViewer').classList.contains('chrome-off'), paused: document.querySelector('#mvContent video').paused, ov: getComputedStyle(document.querySelector('.mv-overlay')).opacity, pe: getComputedStyle(document.querySelector('.mv-ctl')).pointerEvents }));
  ok('点一下：按键收起', s1.off && parseFloat(s1.ov) < 0.05 && s1.pe === 'none', JSON.stringify(s1));
  ok('点一下：不再暂停', !s1.paused, JSON.stringify(s1));
  await tap();
  const s2 = await page.evaluate(() => ({ off: document.querySelector('#mediaViewer').classList.contains('chrome-off'), paused: document.querySelector('#mvContent video').paused }));
  ok('再点一下：按键回来', !s2.off, JSON.stringify(s2));
  ok('再点一下：仍然在播', !s2.paused, JSON.stringify(s2));
  await page.evaluate(() => { const b = document.querySelector('[data-mvact="playpause"]'); if (b) b.click(); });
  await sleep(500);
  const s3 = await page.evaluate(() => ({ off: document.querySelector('#mediaViewer').classList.contains('chrome-off'), paused: document.querySelector('#mvContent video').paused }));
  ok('控制条播放键仍能暂停', !s3.off && s3.paused, JSON.stringify(s3));
  await tap();
  const s4 = await page.evaluate(() => ({ off: document.querySelector('#mediaViewer').classList.contains('chrome-off'), paused: document.querySelector('#mvContent video').paused }));
  ok('暂停状态下点画面也不恢复播放', s4.off && s4.paused, JSON.stringify(s4));
  await tap();
  const s5 = await page.evaluate(() => ({ off: document.querySelector('#mediaViewer').classList.contains('chrome-off'), paused: document.querySelector('#mvContent video').paused }));
  ok('再点一次只显示按键，播放状态不变', !s5.off && s5.paused, JSON.stringify(s5));
  ok('无 pageerror', errs.length === 0, errs.join(' | ').slice(0, 200));
  console.log(log.join('\n'));
  console.log('SUMMARY ' + log.filter(x => x.startsWith('PASS')).length + '/' + log.length);
  await browser.close(); srv.close(); process.exit(0);
})().catch(e => { console.log('FATAL ' + e.message); console.log(log.join('\n')); process.exit(1); });
