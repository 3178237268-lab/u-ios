const { chromium } = require('playwright-core');
const CHROME = 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
const log = [];
const ok = (n, c, extra) => { log.push((c ? 'PASS ' : 'FAIL ') + n + (extra ? ' | ' + extra : '')); };
const sleep = (n) => new Promise(r => setTimeout(r, n));
(async () => {
  const browser = await chromium.launch({ executablePath: CHROME, headless: true, args: ['--no-sandbox', '--disable-gpu', '--autoplay-policy=no-user-gesture-required'] });
  const ctx = await browser.newContext({ viewport: { width: 420, height: 900 }, deviceScaleFactor: 2 });
  const page = await ctx.newPage();
  const errs = []; page.on('pageerror', e => errs.push(String(e)));
  await page.goto('http://127.0.0.1:8765/index.html');
  await page.evaluate(() => localStorage.setItem('u-server', 'http://127.0.0.1:8787'));
  await page.reload(); await sleep(700);
  await page.fill('#authUser', 'admin123'); await page.fill('#authPass', 'admin123');
  await page.click('#authSubmit'); await sleep(3000);
  const pid = await page.evaluate(() => {
    const a = Array.from(document.querySelectorAll('.post')).find(x => x.querySelectorAll('.vplayer.vgrid').length >= 2);
    return a ? a.dataset.id : null;
  });
  ok('线上有多视频帖', !!pid, String(pid));
  if (!pid) { console.log(log.join('\n')); await browser.close(); process.exit(1); }
  await page.evaluate((id) => { document.querySelector('.post[data-id="' + id + '"]').scrollIntoView({ block: 'center' }); }, pid);
  await sleep(600);
  await page.evaluate((id) => { const a = document.querySelector('.post[data-id="' + id + '"]'); (a.querySelector('.vgexp') || a.querySelector('.vplayer')).click(); }, pid);
  await page.waitForSelector('#mediaViewer.open', { timeout: 8000 }); await sleep(1600);
  const box = await page.locator('#mvStage').boundingBox();
  const cx = box.x + box.width / 2, cy = box.y + box.height * 0.42;
  await page.mouse.move(cx, cy); await page.mouse.down(); await sleep(60); await page.mouse.up(); await sleep(500);
  const s1 = await page.evaluate(() => ({ off: document.querySelector('#mediaViewer').classList.contains('chrome-off'), paused: document.querySelector('#mvContent video').paused, ov: getComputedStyle(document.querySelector('.mv-overlay')).opacity, pe: getComputedStyle(document.querySelector('.mv-ctl')).pointerEvents }));
  ok('线上：点一下暂停并收起按键', s1.off && s1.paused && parseFloat(s1.ov) < .05 && s1.pe === 'none', JSON.stringify(s1));
  await page.screenshot({ path: 'D:/deepseek/gouzuoqu/U/.tmp-test/mv60-live-hidden.png' });
  await page.mouse.move(cx, cy); await page.mouse.down(); await sleep(60); await page.mouse.up(); await sleep(700);
  const s2 = await page.evaluate(() => ({ off: document.querySelector('#mediaViewer').classList.contains('chrome-off'), paused: document.querySelector('#mvContent video').paused }));
  ok('线上：再点一下恢复并播放', !s2.off && !s2.paused, JSON.stringify(s2));
  const sc = await page.evaluate(() => { const s = document.querySelector('.mv-scrub').getBoundingClientRect(); const p = document.querySelector('.mv-prog').getBoundingClientRect(); const k = document.querySelector('.mv-prog s').getBoundingClientRect(); return { sh: s.height, ph: p.height, kw: k.width, sx: s.x, sy: s.y, sw: s.width }; });
  ok('线上：进度条热区 26 / 条 6 / 滑块 15', sc.sh >= 24 && sc.ph >= 5 && sc.kw >= 12, JSON.stringify(sc));
  const t0 = await page.evaluate(() => document.querySelector('#mvContent video').currentTime);
  await page.mouse.move(sc.sx + sc.sw * 0.7, sc.sy + sc.sh / 2); await page.mouse.down(); await sleep(250);
  const t1 = await page.evaluate(() => document.querySelector('#mvContent video').currentTime);
  await page.mouse.up(); await sleep(400);
  ok('线上：按住条 70% 立即跳转', Math.abs(t1 - t0) > 1, t0.toFixed(1) + ' -> ' + t1.toFixed(1));
  await page.mouse.move(cx, cy);
  await page.mouse.down();
  for (let i = 1; i <= 6; i++) { await page.mouse.move(cx, cy - i * 20); await sleep(26); }
  const dg = await page.evaluate(() => document.querySelector('#mvContent').style.transform);
  await page.mouse.up(); await sleep(1000);
  const cnt = await page.evaluate(() => document.querySelector('#mvCount').textContent);
  ok('线上：拖动 1:1 跟手', /translateY\(-1[0-4]\dpx\)/.test(dg || '') || /translateY\(-120px\)/.test(dg || ''), dg);
  ok('线上：上滑切到下一个', cnt.indexOf('2/') === 0, cnt);
  ok('线上无 pageerror', errs.length === 0, errs.join(' | ').slice(0, 200));
  console.log(log.join('\n'));
  console.log('SUMMARY ' + log.filter(x => x.startsWith('PASS')).length + '/' + log.length);
  await browser.close(); process.exit(0);
})().catch(e => { console.log('FATAL ' + e.message); console.log(log.join('\n')); process.exit(1); });
