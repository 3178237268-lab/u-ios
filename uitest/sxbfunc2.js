const { chromium } = require('playwright-core');
const wait = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const b = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true });
  const p = await (await b.newContext()).newPage();
  const errs = [], api = [];
  p.on('pageerror', e => errs.push('PAGEERR ' + String(e).slice(0, 140)));
  p.on('console', m => { if (m.type() === 'error') errs.push('CONSOLE ' + m.text().slice(0, 140)); });
  p.on('response', r => { const u = r.url(); if (u.includes('/api/')) api.push(r.status() + ' ' + u.replace(/^https?:\/\/[^/]+/, '').slice(0, 60)); });
  await p.goto('http://127.0.0.1:8765/.tmp-test/preview-sandbox.html', { waitUntil: 'load' });
  await p.waitForTimeout(2500);
  const fr = p.frames().find(f => f.url().includes('index.html'));
  const ok = [], fail = [];
  const step = async (name, fn) => { try { await fn(); ok.push(name); } catch (e) { fail.push(name + ' :: ' + e.message.split('\n')[0].slice(0, 80)); } };
  const L = s => fr.locator(s);
  await step('游客登录', async () => { await L('#guestBtn').click({ timeout: 6000 }); await wait(2000); });
  await step('时间线有帖', async () => { const n = await L('.post').count(); if (!n) throw new Error('0'); });
  await step('打开发帖', async () => { await L('#composeBtn').click({ timeout: 6000 }); await wait(800); });
  await step('发布', async () => { await L('#composeText').fill('沙箱帖 ' + Date.now(), { timeout: 6000 }); await L('#composePublish').click({ timeout: 6000 }); await wait(2500); });
  await step('新帖出现', async () => { const tx = await fr.evaluate(() => (document.querySelector('.post .ptext') || {}).innerText || ''); if (!tx.includes('沙箱帖')) throw new Error('first=' + tx.slice(0, 14)); });
  await step('点赞', async () => { await L('.post button[data-act="like"]').first().click({ timeout: 6000 }); await wait(900); });
  await step('打开详情', async () => { await L('.post .ptext').first().click({ timeout: 6000 }); await wait(1000); });
  await step('回复', async () => { await L('#replyInput').fill('沙箱回复', { timeout: 6000 }); await L('#replySend').click({ timeout: 6000 }); await wait(1500); });
  await step('返回', async () => { await L('#postBack').click({ timeout: 6000 }); await wait(800); });
  await step('搜索', async () => { await L('.tab[data-tab="search"]').click({ timeout: 6000 }); await wait(700); await L('#searchInput').fill('U', { timeout: 6000 }); await wait(1500); });
  await step('设置', async () => { await L('#settingsBtn').click({ timeout: 6000 }); await wait(800); });
  await step('浅色', async () => { await L('button[data-theme="light"]').click({ timeout: 6000 }); await wait(700); const l = await fr.evaluate(() => document.body.classList.contains('light')); if (!l) throw new Error('no light'); });
  await step('关设置', async () => { await L('#settingsClose').click({ timeout: 6000 }); await wait(600); });
  console.log('PASS ' + ok.length + '/' + (ok.length + fail.length)); fail.forEach(f => console.log('FAIL ' + f));
  console.log('api calls', api.length); [...new Set(api)].slice(0, 10).forEach(a => console.log('  ', a));
  console.log('errors', errs.length); errs.slice(0, 8).forEach(e => console.log('  ', e));
  await p.screenshot({ path: 'D:\\deepseek\\gouzuoqu\\U\\.tmp-test\\shots\\sxb3.png' });
  await b.close();
})();
